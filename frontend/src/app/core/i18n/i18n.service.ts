@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly document = inject(DOCUMENT);
  private readonly localeState = signal<AppLocale>(readStoredLocale());

  readonly locale = this.localeState.asReadonly();
  readonly localeTag = computed(() => localeOption(this.locale()).languageTag);
  readonly localeOptions = APP_LOCALES;

  constructor() {
    effect(() => {
      const locale = this.locale();
      this.document.documentElement.lang = localeOption(locale).languageTag;
      persistLocale(locale);
    });
  }

  setLocale(locale: AppLocale): void {
    this.localeState.set(locale);
  }

  translate(key: TranslationKey, parameters: Readonly<Record<string, string | number>> = {}): string {
    return interpolate(TRANSLATIONS[this.locale()][key], parameters);
  }

  navigationLabel(id: string, fallback: string): string {
    const key = `nav.${id}` as TranslationKey;
    return key in ENGLISH_TRANSLATIONS ? this.translate(key) : fallback;
  }

  accountStatusLabel(status: 'active' | 'disabled' | 'deleted'): string {
    return this.translate(`account.status.${status}` as TranslationKey);
  }

  accountStatusMessage(status: 'active' | 'disabled' | 'deleted'): string {
    return this.translate(`account.status.${status}Message` as TranslationKey);
  }

  formatDateTime(value: Date | string | number, options: Intl.DateTimeFormatOptions = {}): string {
    const date = value instanceof Date ? value : new Date(value);
    return Number.isNaN(date.getTime()) ? '' : new Intl.DateTimeFormat(this.localeTag(), options).format(date);
  }

  formatNumber(value: number, options: Intl.NumberFormatOptions = {}): string {
    return new Intl.NumberFormat(this.localeTag(), options).format(value);
  }

  formatFileSize(bytes: number): string {
    const safeBytes = Math.max(0, bytes);
    const divisor = safeBytes >= 1024 * 1024 ? 1024 * 1024 : 1024;
    const unit = divisor === 1024 * 1024 ? 'MB' : 'KB';
    const value = Math.max(1, Math.round(safeBytes / divisor));
    return `${this.formatNumber(value)  } ${  unit}`;
  }

  fileContentTypeLabel(contentType: string): string {
    const normalized = contentType.split(';', 1)[0]?.trim().toLowerCase() ?? '';
    if (normalized === 'application/pdf') {return this.translate('files.type.pdf');}
    if (normalized === 'text/csv') {return this.translate('files.type.spreadsheet');}
    if (normalized.startsWith('text/')) {return this.translate('files.type.text');}
    if (normalized.startsWith('image/')) {return this.translate('files.type.image');}
    if (normalized.startsWith('video/')) {return this.translate('files.type.video');}
    if (normalized.startsWith('audio/')) {return this.translate('files.type.audio');}
    if (['application/zip', 'application/x-zip-compressed', 'application/x-7z-compressed', 'application/x-rar-compressed', 'application/gzip', 'application/x-tar'].includes(normalized)) {return this.translate('files.type.archive');}
    if (['application/msword', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', 'application/rtf', 'application/vnd.oasis.opendocument.text'].includes(normalized)) {return this.translate('files.type.document');}
    if (['application/vnd.ms-excel', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'text/csv', 'application/vnd.oasis.opendocument.spreadsheet'].includes(normalized)) {return this.translate('files.type.spreadsheet');}
    return this.translate('files.type.other');
  }

  fileScanStatusLabel(status: 'pending' | 'allowed' | 'blocked' | 'unavailable'): string {
    return this.translate((`files.scan.${  status}`) as TranslationKey);
  }

  taskFileScanStatusLabel(status: string): string {
    const normalized = status.trim().toLowerCase();
    if (normalized === 'clean' || normalized === 'allowed') {return this.fileScanStatusLabel('allowed');}
    if (normalized === 'infected' || normalized === 'blocked') {return this.fileScanStatusLabel('blocked');}
    if (normalized === 'pending' || normalized === 'scanpending') {return this.fileScanStatusLabel('pending');}
    return this.fileScanStatusLabel('unavailable');
  }

  taskFileAccessStateLabel(accessState: string): string {
    const normalized = accessState.trim().toLowerCase();
    const key: TranslationKey = normalized === 'available'
      ? 'files.task.access.available'
      : normalized === 'missing'
        ? 'files.task.access.missing'
        : normalized === 'quarantined'
          ? 'files.task.access.quarantined'
          : normalized === 'scanpending'
            ? 'files.task.access.scanPending'
            : normalized === 'accessrevoked'
              ? 'files.task.access.revoked'
              : 'files.task.access.unavailable';
    return this.translate(key);
  }

  taskFileRestrictionLabel(restrictionCode: string | null | undefined): string | null {
    if (!restrictionCode) {return null;}
    const normalized = restrictionCode.trim().toUpperCase();
    const key: TranslationKey = normalized === 'FILE_MISSING' || normalized === 'FILE_ARCHIVED'
      ? 'files.task.access.missing'
      : normalized === 'QUARANTINED'
        ? 'files.task.access.quarantined'
        : normalized === 'SCAN_PENDING'
          ? 'files.task.access.scanPending'
          : normalized === 'ACCESS_REVOKED'
            ? 'files.task.access.revoked'
            : 'files.task.access.unavailable';
    return this.translate(key);
  }

  fileUploadStateLabel(state: 'pending' | 'uploading' | 'succeeded' | 'failed' | 'cancelled'): string {
    return this.translate((`files.upload.${  state}`) as TranslationKey);
  }

  agGridLocaleText(): Readonly<Record<string, string>> {
    return this.locale() === 'ja' ? AG_GRID_JAPANESE_LOCALE_TEXT : {};
  }

  syncfusionLocale(): 'en-US' | 'ja' {
    return this.locale() === 'ja' ? 'ja' : 'en-US';
  }

  apiErrorMessage(
    error: Readonly<{ httpStatus: number; message: string }>,
    fallback: TranslationKey = 'api.requestFailed',
  ): string {
    if (this.locale() === 'en') {
      return error.message || this.translate(fallback);
    }

    const key = ({
      401: 'api.authenticationRequired',
      403: 'api.permissionDenied',
      404: 'api.notFound',
      409: 'api.conflict',
      429: 'api.rateLimited',
      500: 'api.serverError',
    } as const)[error.httpStatus] ?? fallback;
    return this.translate(key);
  }
}

function localeOption(locale: AppLocale): AppLocaleOption {
  return APP_LOCALES.find((option) => option.value === locale) ?? APP_LOCALES[0];
}

function readStoredLocale(): AppLocale {
  try {
    return window.localStorage.getItem(LOCALE_STORAGE_KEY) === 'en' ? 'en' : 'ja';
  } catch {
    return 'ja';
  }
}

function persistLocale(locale: AppLocale): void {
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // A blocked browser storage area must not prevent the application rendering.
  }
}

function interpolate(template: string, parameters: Readonly<Record<string, string | number>>): string {
  return template.replace(new RegExp('[{][{](\\w+)[}][}]', 'gu'), (match, key: string) => String(parameters[key] ?? match));
}
